const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=(f)=>fs.readFileSync(path.join(root,f),'utf8');
test('company job detail uses common modern detail view and preserves real job source',()=>{
 const page=read('app/admin/jobs/[id]/page.tsx');
 const view=read('app/components/workspace/MasterJobDetailView.tsx');
 assert.match(page,/MasterJobDetailView/);
 assert.match(page,/\.from\('jobs'\)/);
 assert.match(page,/canManage=\{canManage\}/);
 const gate=read('app/admin/Company3150LayoutGate.tsx');
 const master=read('app/try-xdrive-demo/components/OperationsDemo.tsx');
 assert.match(gate,/MasterWorkspace role="Company \/ Carrier" authenticated initialTab=\{2\} dashboard=\{children\}/);
 assert.match(master,/dashboard&&tab===initialTab\?dashboard/);
 assert.match(view,/Load Details/);
 assert.match(view,/POD & Documents/);
 assert.match(view,/Status History/);
 assert.match(view,/!delivered/);
 assert.match(view,/No POD evidence recorded/);
 assert.match(view,/\/api\/pod\/signed-url/);
});
test('POD storage signing authorizes pickup plus delivery photo paths against job',()=>{
 const api=read('app/api/pod/signed-url/route.ts');
 assert.match(api,/pickup_photos, collection_photo_url/);
 assert.match(api,/permittedPaths\.has\(objectPath\)/);
 assert.match(api,/company_memberships/);
 assert.match(api,/createSignedUrl\(objectPath, 120\)/);
});
