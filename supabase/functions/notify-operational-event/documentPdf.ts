import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
type PdfLine = {
  text: string;
  bold?: boolean;
  size?: number;
  gapBefore?: number;
};

export type EmailAttachment = {
  filename: string;
  content: string;
  content_type?: string;
};

const ascii = (value: unknown) =>
  String(value ?? '')
    .replaceAll('£', 'GBP ')
    .replaceAll('–', '-')
    .replaceAll('—', '-')
    .replaceAll('→', '->')
    .replaceAll('’', "'")
    .replaceAll('“', '"')
    .replaceAll('”', '"')
    .normalize('NFKD')
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const pdfEscape = (value: string) =>
  value.replaceAll('\\', '\\\\').replaceAll('(', '\\(').replaceAll(')', '\\)');

const wrap = (value: string, width = 82) => {
  const text = ascii(value);
  if (!text) return [''];
  const words = text.split(' ');
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    if (!current) {
      current = word;
      continue;
    }
    if ((current + ' ' + word).length <= width) {
      current += ' ' + word;
    } else {
      lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines;
};

const bytesToBase64 = (bytes: Uint8Array) => {
  let binary = '';
  const chunk = 0x8000;
  for (let offset = 0; offset < bytes.length; offset += chunk) {
    binary += String.fromCharCode(...bytes.subarray(offset, Math.min(offset + chunk, bytes.length)));
  }
  return btoa(binary);
};

const buildPdfBytes = (title: string, subtitle: string, lines: PdfLine[]) => {
  const content: string[] = [];
  content.push('0.08 0.24 0.48 rg');
  content.push('BT /F2 19 Tf 50 790 Td (XDrive Logistics) Tj ET');
  content.push('0.05 0.12 0.22 rg');
  content.push(`BT /F2 17 Tf 50 758 Td (${pdfEscape(ascii(title))}) Tj ET`);
  if (subtitle) {
    content.push('0.30 0.36 0.44 rg');
    content.push(`BT /F1 9 Tf 50 739 Td (${pdfEscape(ascii(subtitle))}) Tj ET`);
  }
  content.push('0.78 0.82 0.88 RG 0.8 w 50 724 m 545 724 l S');

  let y = 704;
  for (const line of lines) {
    y -= line.gapBefore ?? 0;
    const size = line.size ?? 10;
    const font = line.bold ? 'F2' : 'F1';
    const wrapped = wrap(line.text, line.bold ? 76 : 86);
    for (const part of wrapped) {
      if (y < 70) break;
      content.push(line.bold ? '0.05 0.12 0.22 rg' : '0.16 0.20 0.27 rg');
      content.push(`BT /${font} ${size} Tf 50 ${y} Td (${pdfEscape(part)}) Tj ET`);
      y -= Math.max(14, size + 4);
    }
    if (y < 70) break;
  }

  content.push('0.78 0.82 0.88 RG 0.6 w 50 48 m 545 48 l S');
  content.push('0.38 0.43 0.50 rg');
  content.push('BT /F1 8 Tf 50 34 Td (Generated by XDrive Logistics. Keep this document with the related XDrive record.) Tj ET');

  const stream = content.join('\n') + '\n';
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
    `<< /Length ${stream.length} >>\nstream\n${stream}endstream`,
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  for (let index = 0; index < objects.length; index += 1) {
    offsets[index + 1] = pdf.length;
    pdf += `${index + 1} 0 obj\n${objects[index]}\nendobj\n`;
  }
  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let index = 1; index <= objects.length; index += 1) {
    pdf += String(offsets[index]).padStart(10, '0') + ' 00000 n \n';
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  return new TextEncoder().encode(pdf);
};

const field = (label: string, value: unknown): PdfLine[] => {
  const cleaned = ascii(value);
  if (!cleaned) return [];
  return [{ text: label, bold: true, size: 9, gapBefore: 5 }, { text: cleaned, size: 10 }];
};

export type BookingDocumentContext = {
  reference: string;
  statusLabel: string;
  buyerName?: string;
  carrierName?: string;
  pickup?: string;
  pickupDateTime?: string;
  delivery?: string;
  deliveryDateTime?: string;
  customerReference?: string;
  purchaseOrderNumber?: string;
  vehicle?: string;
  cargo?: string;
  distanceMiles?: number | null;
  agreedRate?: number | null;
  currency?: string;
  paymentTerms?: string;
  notes?: string;
  hardCopyPod?: string;
};

export function buildBookingAttachments(context: BookingDocumentContext): EmailAttachment[] {
  const currency = ascii(context.currency || 'GBP') || 'GBP';
  const rate = typeof context.agreedRate === 'number' && Number.isFinite(context.agreedRate)
    ? `${currency} ${context.agreedRate.toFixed(2)}`
    : '';

  const confirmationLines: PdfLine[] = [
    ...field('Booking reference', context.reference),
    ...field('Status', context.statusLabel),
    ...field('Received from', context.buyerName),
    ...field('Sub-contracted to', context.carrierName),
    ...field('Pickup', [context.pickupDateTime, context.pickup].filter(Boolean).join(' - ')),
    ...field('Delivery', [context.deliveryDateTime, context.delivery].filter(Boolean).join(' - ')),
    ...field('Customer reference', context.customerReference),
    ...field('Purchase order', context.purchaseOrderNumber),
    ...field('Vehicle', context.vehicle),
    ...field('Cargo', context.cargo),
    ...field('Distance', typeof context.distanceMiles === 'number' ? `${context.distanceMiles.toFixed(1)} miles` : ''),
    ...field('Agreed rate', rate),
    ...field('Payment terms', context.paymentTerms),
    ...field('Hard-copy POD', context.hardCopyPod),
    ...field('Booking notes', context.notes),
  ];

  const deliveryLines: PdfLine[] = [
    ...field('Booking reference', context.reference),
    ...field('Collection', [context.pickupDateTime, context.pickup].filter(Boolean).join(' - ')),
    ...field('Delivery', [context.deliveryDateTime, context.delivery].filter(Boolean).join(' - ')),
    ...field('Vehicle', context.vehicle),
    ...field('Cargo', context.cargo),
    ...field('Instructions', context.notes),
    { text: 'COLLECTION HANDOVER', bold: true, size: 11, gapBefore: 16 },
    { text: 'Collected by: ______________________________    Time: __________', size: 10 },
    { text: 'Collection notes: _____________________________________________', size: 10, gapBefore: 6 },
    { text: 'DELIVERY HANDOVER', bold: true, size: 11, gapBefore: 18 },
    { text: 'Received by: ______________________________    Time: __________', size: 10 },
    { text: 'Signature / confirmation: _____________________________________', size: 10, gapBefore: 6 },
  ];

  const confirmation = buildPdfBytes(
    context.statusLabel,
    `Booking ${ascii(context.reference)}`,
    confirmationLines,
  );
  const deliveryNote = buildPdfBytes(
    'Delivery Note',
    `Booking ${ascii(context.reference)}`,
    deliveryLines,
  );

  const safeRef = ascii(context.reference).replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'booking';
  return [
    {
      filename: `${safeRef}_booking_confirmation.pdf`,
      content: bytesToBase64(confirmation),
      content_type: 'application/pdf',
    },
    {
      filename: `${safeRef}_delivery_note.pdf`,
      content: bytesToBase64(deliveryNote),
      content_type: 'application/pdf',
    },
  ];
}

export type PodDocumentContext = {
  reference: string;
  pickup?: string;
  delivery?: string;
  deliveredOn?: string;
  receivedBy?: string;
  leftAt?: string;
  deliveryStatus?: string;
  itemCount?: number | null;
  deliveryNotes?: string;
};

export function buildPodSummaryAttachment(context: PodDocumentContext): EmailAttachment {
  const lines: PdfLine[] = [
    ...field('Booking reference', context.reference),
    ...field('From', context.pickup),
    ...field('To', context.delivery),
    ...field('Delivered on', context.deliveredOn),
    ...field('Received by', context.receivedBy),
    ...field('Left at', context.leftAt),
    ...field('Delivery status', context.deliveryStatus),
    ...field('Items', typeof context.itemCount === 'number' ? context.itemCount : ''),
    ...field('Delivery notes', context.deliveryNotes),
    { text: 'Evidence files supplied with this email form part of this POD record.', size: 9, gapBefore: 18 },
  ];
  const bytes = buildPdfBytes('Proof of Delivery', `Booking ${ascii(context.reference)}`, lines);
  const safeRef = ascii(context.reference).replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'booking';
  return {
    filename: `${safeRef}_POD.pdf`,
    content: bytesToBase64(bytes),
    content_type: 'application/pdf',
  };
}

export type RemittanceDocumentContext = {
  invoiceNumber: string;
  jobReference?: string;
  pickup?: string;
  delivery?: string;
  serviceDescription?: string;
  supplierName?: string;
  customerName?: string;
  paymentDate?: string;
  amount?: number | null;
  currency?: string;
  paymentReference?: string;
  settlementMethod?: string;
};

export async function buildRemittanceAdviceAttachment(context: RemittanceDocumentContext, officialLogoBytes?: Uint8Array): Promise<EmailAttachment> {
  const currency = ascii(context.currency || 'GBP') || 'GBP';
  const amount = typeof context.amount === 'number' && Number.isFinite(context.amount)
    ? `${currency} ${context.amount.toFixed(2)}`
    : '';
  const lines: PdfLine[] = [
    ...field('Invoice', context.invoiceNumber),
    ...field('Job reference', context.jobReference),
    ...field('Collection', context.pickup),
    ...field('Delivery', context.delivery),
    ...field('Transport service', context.serviceDescription),
    ...field('Supplier', context.supplierName),
    ...field('Customer', context.customerName),
    ...field('Payment date', context.paymentDate),
    ...field('Payment recorded', amount),
    ...field(context.paymentReference?.startsWith('pi_') ? 'Stripe PaymentIntent ID (reconciliation)' : 'External payment reference', context.paymentReference),
    ...field('Payment method', context.settlementMethod),
    { text: 'Payment recorded in XDrive. This document is not confirmation that funds have reached the supplier bank account.', size: 9, gapBefore: 18 },
  ];
  // Official logo is the same canonical PNG used by the Invoice and POD generators.
  // Never substitute a wordmark or silently create a differently branded PDF.
  const logoBytes = officialLogoBytes ?? new Uint8Array(await (async () => {
    const response = await fetch('https://www.xdrivelogistics.co.uk/xdrive-logo-primary.png');
    if (!response.ok) throw new Error('Official XDrive logo unavailable for remittance PDF');
    return response.arrayBuffer();
  })());
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595, 842]);
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const logo = await pdf.embedPng(logoBytes);
  const scaled = logo.scaleToFit(204, 62);
  page.drawImage(logo, { x: 48, y: 756, width: scaled.width, height: scaled.height });
  const navy = rgb(0.039, 0.149, 0.326);
  const grey = rgb(0.32, 0.39, 0.48);
  page.drawText('REMITTANCE ADVICE', { x: 48, y: 728, size: 17, font: bold, color: navy });
  page.drawText('Invoice ' + ascii(context.invoiceNumber), { x: 48, y: 711, size: 10, font: regular, color: grey });
  page.drawLine({ start: { x: 48, y: 698 }, end: { x: 547, y: 698 }, thickness: 1, color: rgb(.82,.86,.91) });
  let y = 678;
  for (const line of lines) {
    y -= line.gapBefore ?? 0;
    const font = line.bold ? bold : regular;
    const size = line.size ?? 10;
    const text = ascii(line.text);
    if (!text) continue;
    let current = '';
    for (const word of text.split(' ')) {
      const next = current ? current + ' ' + word : word;
      if (font.widthOfTextAtSize(next, size) > 490 && current) {
        if (y < 58) throw new Error('Remittance content exceeds a single PDF page');
        page.drawText(current, { x: 48, y, size, font, color: line.bold ? navy : grey });
        y -= 14;
        current = word;
      } else current = next;
    }
    if (y < 58) throw new Error('Remittance content exceeds a single PDF page');
    page.drawText(current, { x: 48, y, size, font, color: line.bold ? navy : grey });
    y -= Math.max(14, size + 4);
  }
  page.drawLine({ start: { x: 48, y: 46 }, end: { x: 547, y: 46 }, thickness: .7, color: rgb(.82,.86,.91) });
  page.drawText('Generated by XDrive Logistics - payment record, not bank payout confirmation.', { x: 48, y: 32, size: 8, font: regular, color: grey });
  const bytes = await pdf.save();
  const safeRef = ascii(context.invoiceNumber).replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'invoice';
  return {
    filename: `${safeRef}_remittance.pdf`,
    content: bytesToBase64(bytes),
    content_type: 'application/pdf',
  };
}

export function binaryToBase64(bytes: Uint8Array) {
  return bytesToBase64(bytes);
}
